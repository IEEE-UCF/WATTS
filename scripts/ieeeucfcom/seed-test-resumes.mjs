// Dev helper: seed résumés so you can exercise /admin/resumes and the bulk export.
//
//   node scripts/ieeeucfcom/seed-test-resumes.mjs      (or: pnpm seed:resumes)
//
// What it does (idempotent — safe to re-run):
//   1. creates member "Resume Tester" (a plain member, NOT an officer) with the
//      `upload_resume` + `review_resumes` capability grants
//   2. generates a one-page PDF for Resume Tester and three existing seed members
//      (John Doe, Jane Smith, Peter Jones), uploads them to the private bucket, and
//      sets the résumé columns — exactly what storage.confirmResume writes
//   3. mints a database session for the dev admin (admin@watts.local) and prints a
//      cookie + curl commands so you can hit the export without a Discord login
//
// Requires: local infra up (`pnpm infra:up`) and the base seed (`pnpm db:seed`).

import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes, randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';

// This script has no node_modules of its own — resolve pg / aws-sdk / pdf-lib
// from the website app, which already depends on all three.
const appRequire = createRequire(new URL('../../apps/ieeeucfcom/package.json', import.meta.url));
const pg = appRequire('pg');
const { S3Client, PutObjectCommand } = appRequire('@aws-sdk/client-s3');
const { PDFDocument, StandardFonts, rgb } = appRequire('pdf-lib');

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '../..');

// --- minimal .env reader (no dotenv dependency) ---
function loadEnv(file) {
	let text;
	try {
		text = readFileSync(file, 'utf8');
	} catch {
		return;
	}
	for (const line of text.split('\n')) {
		const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/i);
		if (!m) continue;
		const key = m[1];
		let val = m[2].replace(/\s+#.*$/, '').trim().replace(/^["']|["']$/g, '');
		if (!(key in process.env)) process.env[key] = val;
	}
}
loadEnv(resolve(ROOT, '.env'));
loadEnv(resolve(ROOT, '.env.local'));

const {
	DATABASE_URL,
	S3_ENDPOINT = 'http://127.0.0.1:3052',
	S3_REGION = 'us-east-1',
	S3_ACCESS_KEY_ID = 'minioadmin',
	S3_SECRET_ACCESS_KEY = 'minioadmin',
	S3_BUCKET_PRIVATE = 'resumes-private',
	DEV_ADMIN_EMAIL = 'admin@watts.local',
	NEXTAUTH_URL = 'https://localhost:3050',
} = process.env;

if (!DATABASE_URL) {
	console.error('DATABASE_URL is not set (looked in ./.env). Run `pnpm bootstrap` first.');
	process.exit(1);
}

const db = new pg.Client({ connectionString: DATABASE_URL });
const s3 = new S3Client({
	endpoint: S3_ENDPOINT,
	region: S3_REGION,
	forcePathStyle: true,
	credentials: { accessKeyId: S3_ACCESS_KEY_ID, secretAccessKey: S3_SECRET_ACCESS_KEY },
});

async function makeResumePdf({ name, major, gradYear }) {
	const doc = await PDFDocument.create();
	const page = doc.addPage([612, 792]);
	const bold = await doc.embedFont(StandardFonts.HelveticaBold);
	const font = await doc.embedFont(StandardFonts.Helvetica);
	page.drawText(name, { x: 56, y: 712, size: 28, font: bold });
	page.drawText(`${major}  ·  Class of ${gradYear}`, { x: 56, y: 680, size: 12, font, color: rgb(0.35, 0.35, 0.35) });
	page.drawText('— test résumé generated by seed-test-resumes.mjs —', { x: 56, y: 650, size: 10, font, color: rgb(0.6, 0.6, 0.6) });
	for (let i = 0; i < 6; i++) {
		page.drawText('Experience  •  Lorem ipsum dolor sit amet, consectetur adipiscing elit.', {
			x: 56,
			y: 610 - i * 22,
			size: 11,
			font,
		});
	}
	return Buffer.from(await doc.save());
}

async function putResume(key, bytes) {
	await s3.send(
		new PutObjectCommand({
			Bucket: S3_BUCKET_PRIVATE,
			Key: key,
			Body: bytes,
			ContentType: 'application/pdf',
		}),
	);
}

/** Attach a freshly generated résumé to an existing member row. */
async function attachResume(memberId, key, personLabel) {
	const { rows } = await db.query(
		`select first_name, last_name, major, graduation_year from members where id = $1`,
		[memberId],
	);
	if (!rows[0]) {
		console.log(`  ! member ${memberId} (${personLabel}) not found — skipped`);
		return;
	}
	const m = rows[0];
	const bytes = await makeResumePdf({
		name: `${m.first_name} ${m.last_name}`,
		major: m.major,
		gradYear: m.graduation_year,
	});
	await putResume(key, bytes);
	await db.query(
		`update members
		   set resume_key = $1,
		       resume_url = $2,
		       resume_file_name = $3,
		       resume_uploaded_at = now(),
		       updated_at = now()
		 where id = $4`,
		[key, `/api/files/resume/${memberId}`, `${m.last_name}-${m.first_name}.pdf`, memberId],
	);
	console.log(`  ✓ ${m.first_name} ${m.last_name}  ->  ${key} (${bytes.length} bytes)`);
}

async function main() {
	await db.connect();

	// ---------------------------------------------------------------- resume_tester
	const TESTER_EMAIL = 'resume_tester@watts.local';
	const TESTER_DISCORD = 'resume-tester';

	let { rows: u } = await db.query(`select id from users where email = $1`, [TESTER_EMAIL]);
	let testerUserId = u[0]?.id;
	if (!testerUserId) {
		({ rows: u } = await db.query(
			`insert into users (name, email, discord_id) values ($1,$2,$3) returning id`,
			['Resume Tester', TESTER_EMAIL, TESTER_DISCORD],
		));
		testerUserId = u[0].id;
		console.log(`• created user resume_tester (${TESTER_EMAIL})`);
	} else {
		console.log(`• user resume_tester already present`);
	}

	await db.query(
		`insert into accounts (user_id, type, provider, provider_account_id)
		 values ($1,'oauth','discord',$2)
		 on conflict do nothing`,
		[testerUserId, TESTER_DISCORD],
	);

	let { rows: mem } = await db.query(`select id from members where user_id = $1`, [testerUserId]);
	let testerMemberId = mem[0]?.id;
	if (!testerMemberId) {
		({ rows: mem } = await db.query(
			`insert into members
			   (user_id, discord_id, first_name, last_name, date_of_birth,
			    personal_email, ucf_email, major, gender, graduation_year,
			    administrator, officer_status)
			 values ($1,$2,'Resume','Tester','2003-03-03',$3,$4,
			         'Computer Science (BS)','PNTS',2026,false,false)
			 returning id`,
			[testerUserId, TESTER_DISCORD, TESTER_EMAIL, 'resume.tester@ucf.edu'],
		));
		testerMemberId = mem[0].id;
		console.log(`• created member Resume Tester (plain member, no officer status)`);
	} else {
		console.log(`• member Resume Tester already present`);
	}

	for (const perm of ['upload_resume', 'review_resumes']) {
		await db.query(
			`insert into member_permissions (member_id, context_type, permission, active)
			 values ($1,'global',$2,true)
			 on conflict (member_id, context_type, context_id, permission) do update set active = true`,
			[testerMemberId, perm],
		);
	}
	console.log(`• granted Resume Tester: upload_resume, review_resumes`);

	// ---------------------------------------------------------------- résumé files
	console.log('\nattaching résumés:');
	await attachResume(testerMemberId, `resumes/${testerUserId}.pdf`, 'Resume Tester');
	// existing base-seed members (from infra/seed/fixtures/members.json):
	//   John Doe    — officer + admin, 2025, Computer Science  (tests "include officers")
	//   Jane Smith  — officer,         2026, Electrical Eng
	//   Peter Jones — plain member,    2027, Computer Eng
	await attachResume('a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11', 'resumes/seed-john-doe.pdf', 'John Doe');
	await attachResume('a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a12', 'resumes/seed-jane-smith.pdf', 'Jane Smith');
	await attachResume('a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a13', 'resumes/seed-peter-jones.pdf', 'Peter Jones');

	// ---------------------------------------------------------------- admin session
	const { rows: admin } = await db.query(`select id from users where email = $1`, [DEV_ADMIN_EMAIL]);
	if (!admin[0]) {
		console.log(`\n! No dev admin user (${DEV_ADMIN_EMAIL}). Run \`pnpm db:seed\` then re-run this.`);
	} else {
		const token = randomBytes(32).toString('hex');
		const expires = new Date(Date.now() + 30 * 24 * 3600 * 1000);
		await db.query(`insert into sessions (session_token, user_id, expires) values ($1,$2,$3)`, [
			token,
			admin[0].id,
			expires,
		]);
		const secure = NEXTAUTH_URL.startsWith('https://');
		const cookieName = secure ? '__Secure-next-auth.session-token' : 'next-auth.session-token';
		const base = NEXTAUTH_URL.replace(/\/$/, '');
		console.log('\n──────────────────────────────────────────────────────────────');
		console.log('Dev admin session minted. Test the export without a Discord login:');
		console.log(`\n  cookie:  ${cookieName}=${token}`);
		console.log('\n  # zip of individual PDFs');
		console.log(`  curl -k -OJ --cookie "${cookieName}=${token}" ${base}/api/files/resume/export`);
		console.log('\n  # one merged PDF');
		console.log(`  curl -k -OJ --cookie "${cookieName}=${token}" "${base}/api/files/resume/export?format=pdf"`);
		console.log('\n  Or paste the cookie into DevTools ▸ Application ▸ Cookies and open');
		console.log(`  ${base}/admin/resumes`);
		console.log('──────────────────────────────────────────────────────────────');
	}

	console.log('\n✅ done');
}

main()
	.catch((e) => {
		console.error(e);
		process.exitCode = 1;
	})
	.finally(() => db.end());
